"""Optional maintenance helper; generated src/fonts.js is committed to Git.

Needs fontTools and the three DejaVu files below. Not used during deployment.
Vector subsets are renamed Dobra fonts, under the bundled Bitstream Vera license.
"""
import json
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen

ROOT = Path(__file__).resolve().parents[1]
FONT_ROOT = Path('/usr/share/fonts/truetype/dejavu')
FONT_FILES = {'serif': 'DejaVuSerif.ttf', 'sans': 'DejaVuSans.ttf', 'bold': 'DejaVuSans-Bold.ttf'}
CHARS = ''.join(map(chr, list(range(32, 127)) + list(range(160, 384)) + [0x2013,0x2014,0x2018,0x2019,0x201c,0x201d,0x2022,0x2026,0x2605,0x2606,0x2661,0x2665,0x2764]))

class OutlinePen(BasePen):
    def __init__(self, glyphs, units):
        super().__init__(glyphs)
        self.units = units
        self.commands = []
    def point(self, p):
        return [round(v / self.units * 1000, 1) for v in p]
    def _moveTo(self, p): self.commands.append(['M', *self.point(p)])
    def _lineTo(self, p): self.commands.append(['L', *self.point(p)])
    def _curveToOne(self, p1, p2, p3): self.commands.append(['C', *self.point(p1), *self.point(p2), *self.point(p3)])
    def _qCurveToOne(self, p1, p2): self.commands.append(['Q', *self.point(p1), *self.point(p2)])
    def _closePath(self): self.commands.append(['Z'])
    def _endPath(self): pass

fallback = TTFont(FONT_ROOT / FONT_FILES['sans'])
fonts = {}
for key, filename in FONT_FILES.items():
    font = TTFont(FONT_ROOT / filename)
    glyphs = {}
    for char in CHARS:
        current = font if ord(char) in font.getBestCmap() else fallback
        name = current.getBestCmap().get(ord(char))
        if not name: continue
        glyphset = current.getGlyphSet()
        units = current['head'].unitsPerEm
        pen = OutlinePen(glyphset, units)
        glyphset[name].draw(pen)
        glyphs[char] = {'advance':round(current['hmtx'][name][0]/units*1000,1), 'commands':pen.commands}
    fonts[key] = glyphs

text = '''/* Dobra font vector subsets derived from DejaVu. See FONT-LICENSE.txt.
 * Copyright (c) 2003 Bitstream, Inc. DejaVu changes are in the public domain.
 * Generated by scripts/prepare-fonts.py. */
const FONT_PATHS = ''' + json.dumps(fonts, ensure_ascii=False, separators=(',', ':')) + ''';
export const FONT_LIBRARY = [
  {id:'classic',name:'Clássica',glyphs:FONT_PATHS.serif,shear:0},
  {id:'modern',name:'Moderna',glyphs:FONT_PATHS.sans,shear:0},
  {id:'delicate',name:'Delicada',glyphs:FONT_PATHS.serif,shear:.18},
  {id:'bold',name:'Marcante',glyphs:FONT_PATHS.bold,shear:0},
];
'''
(ROOT/'src/fonts.js').write_text(text, encoding='utf-8')
copyright = Path('/usr/share/doc/fonts-dejavu-core/copyright').read_text()
notice = copyright.split('Files: *\n', 1)[1].split('\nFiles: debian/', 1)[0]
(ROOT/'FONT-LICENSE.txt').write_text('Dobra vector font subsets derived from DejaVu fonts.\n\n'+notice+'\n', encoding='utf-8')
print('Generated vector glyphs:',len(fonts),'sets;',len(text.encode()),'bytes')
